/** Interface translation only. Clinical notes and saved response codes stay unchanged. */
export function translate(
  language: Language,
  key: string,
  values: Record<string, string | number> = {},
) {
  const template = (strings[language] as Record<string, string>)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    String(values[name] ?? match),
  );
}

export function formatDateTime(
  value: string | null | undefined,
  language: Language,
) {
  if (!value || !Number.isFinite(Date.parse(value))) return "—";
  return new Intl.DateTimeFormat(language === "en" ? "en-GB" : "zh-TW", {
    timeZone: "Asia/Taipei",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  }).format(new Date(value));
}

/** API errors remain stable for clients; presentation follows the selected language. */
export function localizeError(message: string, language: Language): string {
  const exact = errorKeys[message];
  if (exact) return translate(language, exact);
  // Check the whole message first: conflict and database errors can contain semicolons.
  if (message.includes("; "))
    return message
      .split("; ")
      .map((part) => localizeError(part, language))
      .join("; ");
  const match = message.match(
    /^([A-Z0-9_]+): (missing|non-negative integer required|invalid response code)$/,
  );
  if (match)
    return translate(
      language,
      match[2] === "missing"
        ? "errorFieldMissing"
        : match[2] === "non-negative integer required"
          ? "errorCount"
          : "errorCode",
      { field: match[1] },
    );
  return translate(language, "errorGeneric");
}
